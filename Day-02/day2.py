# Day 2 - Learning Python

# Variables
name = "Janani"
age = 20

print("My name is", name)
print("My age is", age)

# Data types
print(type(name))
print(type(age))

# Arithmetic operators
a = 10
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Type casting
x = "10"
y = int(x)

print("Before casting:", x, type(x))
print("After casting:", y, type(y))
